def airfoil_names() -> tuple[str, ...]:
    return tuple(_RAW_AIRFOILS.keys())


def _parse_coordinates(raw: str) -> list[tuple[float, float]]:
    lines = [line.strip() for line in raw.strip().splitlines() if line.strip()]
    if len(lines) < 2:
        raise ValueError("Airfoil data needs a title and coordinate rows")

    numeric_values: list[float] = []
    for line in lines[1:]:
        for part in line.split():
            try:
                numeric_values.append(float(part))
            except ValueError:
                continue

    points: list[tuple[float, float]] = []
    if len(numeric_values) >= 4:
        upper_count = int(numeric_values[0])
        lower_count = int(numeric_values[1])
        coordinate_values = numeric_values[2:]
        count_matches = (
            upper_count > 1
            and lower_count > 1
            and abs(numeric_values[0] - upper_count) < 1e-9
            and abs(numeric_values[1] - lower_count) < 1e-9
            and len(coordinate_values) >= 2 * (upper_count + lower_count)
        )
        if count_matches:
            raw_points = [
                (coordinate_values[index], coordinate_values[index + 1])
                for index in range(0, 2 * (upper_count + lower_count), 2)
            ]
            upper = raw_points[:upper_count]
            lower = raw_points[upper_count : upper_count + lower_count]
            # Lednicer-format files store upper and lower as LE->TE. Convert
            # to the same closed-loop order as Selig files: upper TE->LE,
            # then lower LE->TE. Some files repeat the LE point on both
            # surfaces; others start the lower side just aft of the LE.
            lower_tail = (
                lower[1:]
                if hypot(upper[0][0] - lower[0][0], upper[0][1] - lower[0][1]) < 1e-8
                else lower
            )
            points = list(reversed(upper)) + lower_tail
            return _dedupe_consecutive(points)

    for index in range(0, len(numeric_values) - 1, 2):
        points.append((numeric_values[index], numeric_values[index + 1]))

    if len(points) < 3:
        raise ValueError("Airfoil needs at least three coordinate points")
    return points


def _is_le_to_te_to_le_loop(points: list[tuple[float, float]]) -> bool:
    if len(points) < 16 or len(points) % 2 != 0:
        return False
    midpoint = len(points) // 2
    return (
        points[0][0] < 1e-6
        and points[midpoint][0] > 1.0 - 1e-6
        and points[-1][0] < 0.01
        and all(points[index][0] <= points[index + 1][0] + 1e-10 for index in range(midpoint))
        and all(
            points[index][0] >= points[index + 1][0] - 1e-10
            for index in range(midpoint + 1, len(points) - 1)
        )
    )


def _dedupe_consecutive(points: list[tuple[float, float]]) -> list[tuple[float, float]]:
    deduped: list[tuple[float, float]] = []
    for point in points:
        if not deduped or hypot(point[0] - deduped[-1][0], point[1] - deduped[-1][1]) > 1e-10:
            deduped.append(point)
    return deduped


def _normalize(points: list[tuple[float, float]]) -> list[tuple[float, float]]:
    min_x = min(x for x, _ in points)
    max_x = max(x for x, _ in points)
    chord = max_x - min_x
    if chord <= 0:
        raise ValueError("Airfoil chord normalization failed")
    leading_edge_y = min(points, key=lambda point: point[0])[1]
    normalized = [((x - min_x) / chord, (y - leading_edge_y) / chord) for x, y in points]
    return _dedupe_consecutive(normalized)


def _resample_closed_loop(
    points: list[tuple[float, float]], point_count: int
) -> list[tuple[float, float]]:
    if point_count < 16 or point_count % 2 != 0:
        raise ValueError("point_count should be at least 16 for a useful airfoil profile")

    upper_surface, lower_surface = _split_surfaces(points)

    upper_count = point_count // 2
    lower_count = point_count - upper_count

    upper_samples: list[tuple[float, float]] = []
    for index in range(upper_count):
        x = leading_edge_clustered_x(index / (upper_count - 1))
        upper_y, _ = _repaired_surface_pair(upper_surface, lower_surface, x)
        upper_samples.append((x, upper_y))

    lower_samples: list[tuple[float, float]] = []
    # Lower surface starts just aft of the LE and ends at the lower TE. The
    # polygon closes lower-TE -> upper-TE, producing a finite trailing-edge face
    # instead of a near-zero sliver.
    for index in range(1, lower_count + 1):
        x = leading_edge_clustered_x(index / lower_count)
        _, lower_y = _repaired_surface_pair(upper_surface, lower_surface, x)
        lower_samples.append((x, lower_y))

    # Keep every generated airfoil in one canonical loop order:
    # upper TE->LE, then lower LE->TE. This puts the loft seam on the trailing
    # edge instead of the nose; the leading edge is high-curvature and was
    # causing ForgeCAD's level-set loft to fan/cut when winglet stations were
    # added.
    return list(reversed(upper_samples)) + lower_samples


def _split_surfaces(
    points: list[tuple[float, float]]
) -> tuple[list[tuple[float, float]], list[tuple[float, float]]]:
    """Return upper/lower lookup surfaces independent of loop seam location."""

    if len(points) < 4:
        raise ValueError("Airfoil loop needs at least four points")

    leading_edge_index = min(range(len(points)), key=lambda index: points[index][0])
    if leading_edge_index == 0 or leading_edge_index == len(points) - 1:
        trailing_edge_index = max(range(len(points)), key=lambda index: points[index][0])
        upper_points = points[: trailing_edge_index + 1]
        lower_points = points[trailing_edge_index:]
    else:
        upper_points = points[: leading_edge_index + 1]
        lower_points = points[leading_edge_index:]

    if len(upper_points) < 2 or len(lower_points) < 2:
        raise ValueError("Airfoil loop could not be split into upper/lower surfaces")
    return _surface_lookup(upper_points), _surface_lookup(lower_points)


def _surface_lookup(surface: list[tuple[float, float]]) -> list[tuple[float, float]]:
    by_x: dict[float, list[float]] = {}
    for x, y in surface:
        key = round(x, 10)
        by_x.setdefault(key, []).append(y)
    lookup = sorted((x, sum(ys) / len(ys)) for x, ys in by_x.items())
    if len(lookup) < 2:
        raise ValueError("Airfoil surface interpolation needs at least two points")
    return lookup


def _interpolate_surface_y(surface: list[tuple[float, float]], x: float) -> float:
    if x <= surface[0][0]:
        return surface[0][1]
    if x >= surface[-1][0]:
        return surface[-1][1]

    for left, right in zip(surface, surface[1:]):
        x0, y0 = left
        x1, y1 = right
        if x0 <= x <= x1:
            span = x1 - x0
            ratio = 0.0 if span <= 0 else (x - x0) / span
            return y0 + (y1 - y0) * ratio

    return surface[-1][1]


def _repaired_surface_pair(
    upper_surface: list[tuple[float, float]],
    lower_surface: list[tuple[float, float]],
    x: float,
) -> tuple[float, float]:
    if x <= 1e-10:
        return 0.0, 0.0
    upper_y = _interpolate_surface_y(upper_surface, x)
    lower_y = _interpolate_surface_y(lower_surface, x)
    te_floor = MIN_TRAILING_EDGE_THICKNESS_FRACTION if x >= 0.95 else 0.0
    required_thickness = max(te_floor, 0.0015 * sin_chord_weight(x))
    if upper_y - lower_y < required_thickness:
        camber_y = (upper_y + lower_y) / 2.0
        return camber_y + required_thickness / 2.0, camber_y - required_thickness / 2.0
    return upper_y, lower_y


def sin_chord_weight(x: float) -> float:
    return max(0.0, sin(pi * max(0.0, min(1.0, x))))


def leading_edge_clustered_x(t: float) -> float:
    t = max(0.0, min(1.0, t))
    # Mild leading-edge clustering. The previous cosine rule put many points
    # within a few hundredths of a millimetre on small tip chords; Fusion rendered
    # those sliver facets like cracks even though the STL was topologically closed.
    return t**1.35


@lru_cache(maxsize=None)
def normalized_airfoil(
    name: str, point_count: int = AIRFOIL_POINT_COUNT
) -> tuple[tuple[float, float], ...]:
    """Return normalized closed-loop coordinates with leading edge at x=0 and chord=1."""

    if name not in _RAW_AIRFOILS:
        raise KeyError(f"Unknown airfoil {name!r}. Available: {', '.join(airfoil_names())}")
    parsed = _parse_coordinates(_RAW_AIRFOILS[name])
    normalized = _normalize(parsed)
    return tuple(_resample_closed_loop(normalized, point_count))


def normalized_airfoil_population(
    names: tuple[str, ...], point_count: int
) -> dict[str, list[list[float]]]:
    return {
        name: [[round(x, 8), round(y, 8)] for x, y in normalized_airfoil(name, point_count)]
        for name in names
    }


def interpolated_airfoil_population_200(
    names: tuple[str, ...] | None = None,
) -> dict[str, tuple[tuple[float, float], ...]]:
    """Return the 200-point profiles used by generated ForgeCAD lofts."""

    selected_names = airfoil_names() if names is None else names
    return {
        name: normalized_airfoil(name, AIRFOIL_POINT_COUNT)
        for name in selected_names
    }
