from __future__ import annotations

import json
from pathlib import Path
from textwrap import dedent
from typing import Any

from .airfoils import normalized_airfoil_population
from .config import GeneratorConfig


def write_design_files(design: dict[str, Any], design_dir: Path, config: GeneratorConfig) -> None:
    design_dir.mkdir(parents=True, exist_ok=True)
    (design_dir / "parameters.json").write_text(
        json.dumps(design, indent=2) + "\n",
        encoding="utf-8",
    )
    (design_dir / "geometry.forge.js").write_text(
        forgecad_source_for_design(design, config),
        encoding="utf-8",
    )


def forgecad_source_for_design(design: dict[str, Any], config: GeneratorConfig) -> str:
    airfoils = normalized_airfoil_population(
        tuple(design["airfoil_population"]),
        config.airfoil_points_per_profile,
    )
    design_json = json.dumps(design, indent=2)
    airfoil_json = json.dumps(airfoils, indent=2)

    return dedent(
        f"""
        // Generated by wing_generator. Metadata is stored in parameters.json.
        // Units in DESIGN are meters/degrees. ForgeCAD geometry is generated in millimeters.

        const DESIGN = {design_json};
        const AIRFOILS = {airfoil_json};

        const MM = 1000.0;
        const DEG = Math.PI / 180.0;

        function rotate2d(x, z, angleDeg) {{
          const a = angleDeg * DEG;
          const c = Math.cos(a);
          const s = Math.sin(a);
          return [x * c - z * s, x * s + z * c];
        }}

        function profileThickness(coords) {{
          let minZ = Infinity;
          let maxZ = -Infinity;
          for (const point of coords) {{
            minZ = Math.min(minZ, point[1]);
            maxZ = Math.max(maxZ, point[1]);
          }}
          return Math.max(maxZ - minZ, 1e-9);
        }}

        function airfoilPoints(section) {{
          const coords = AIRFOILS[section.airfoil_type];
          if (!coords) {{
            throw new Error(`Unknown airfoil type: ${{section.airfoil_type}}`);
          }}

          const zScale = section.target_thickness_m
            ? (section.target_thickness_m * MM) / profileThickness(coords)
            : section.chord_length * MM;
          const points = [];
          for (let i = 0; i < coords.length; i += 1) {{
            const raw = coords[i];
            const scaledX = raw[0] * section.chord_length * MM;
            const scaledZ = raw[1] * zScale;
            const rotated = rotate2d(scaledX, scaledZ, section.root_pitch_angle_deg);
            // The sketch is built in a local XY plane and lofted along Z (spanwise).
            //   sketch-X = chordwise + sweep
            //   sketch-Y = vertical + dihedral
            // A final rotateX(90) maps this to the global frame:
            //   X = chordwise, Y = spanwise, Z = vertical (up).
            points.push([
              rotated[0] + section.horizontal_displacement * MM,
              rotated[1] + section.vertical_displacement * MM,
            ]);
          }}
          return points;
        }}

        function airfoilSketch(section) {{
          return polygon(airfoilPoints(section));
        }}

        function boundsOfPoints(points) {{
          let minX = Infinity;
          let maxX = -Infinity;
          let minY = Infinity;
          let maxY = -Infinity;
          for (const point of points) {{
            minX = Math.min(minX, point[0]);
            maxX = Math.max(maxX, point[0]);
            minY = Math.min(minY, point[1]);
            maxY = Math.max(maxY, point[1]);
          }}
          return {{
            minX,
            maxX,
            minY,
            maxY,
            centerX: 0.5 * (minX + maxX),
            centerY: 0.5 * (minY + maxY),
          }};
        }}

        function stationHeight(section) {{
          // Heights are negated so that, after the final rotateX(90), the wing
          // spans the positive Y axis (loft stacks profiles along Z).
          return -section.spanwise_position * MM;
        }}

        function loftEntry(section) {{
          const points = airfoilPoints(section);
          return {{
            section,
            profile: polygon(points),
            height: stationHeight(section),
            bounds: boundsOfPoints(points),
          }};
        }}

        function hermiteRailValue(t, p0, m0, p1, m1, dz) {{
          const t2 = t * t;
          const t3 = t2 * t;
          const h00 = 2.0 * t3 - 3.0 * t2 + 1.0;
          const h10 = t3 - 2.0 * t2 + t;
          const h01 = -2.0 * t3 + 3.0 * t2;
          const h11 = t3 - t2;
          return h00 * p0 + h10 * dz * m0 + h01 * p1 + h11 * dz * m1;
        }}

        function smoothRail(controlPoints, samplesPerSegment = 6) {{
          // Monotone cubic Hermite in loft-axis Z. This gives the leading,
          // trailing and center rails spline-like continuity while preserving
          // strictly increasing station positions required by ForgeCAD rails.
          const points = [...controlPoints].sort((a, b) => a[2] - b[2]);
          if (points.length < 3) {{
            return points;
          }}

          function slope(i, component) {{
            if (i <= 0) {{
              const dz = Math.max(1e-9, points[1][2] - points[0][2]);
              return (points[1][component] - points[0][component]) / dz;
            }}
            if (i >= points.length - 1) {{
              const last = points.length - 1;
              const dz = Math.max(1e-9, points[last][2] - points[last - 1][2]);
              return (points[last][component] - points[last - 1][component]) / dz;
            }}
            const dz = Math.max(1e-9, points[i + 1][2] - points[i - 1][2]);
            return (points[i + 1][component] - points[i - 1][component]) / dz;
          }}

          const xSlopes = points.map((_, i) => slope(i, 0));
          const ySlopes = points.map((_, i) => slope(i, 1));
          const rail = [points[0]];
          for (let i = 0; i < points.length - 1; i += 1) {{
            const a = points[i];
            const b = points[i + 1];
            const dz = b[2] - a[2];
            const samples = Math.max(2, Math.round(samplesPerSegment));
            for (let s = 1; s <= samples; s += 1) {{
              const t = s / samples;
              const z = a[2] + dz * t;
              const x = hermiteRailValue(t, a[0], xSlopes[i], b[0], xSlopes[i + 1], dz);
              const y = hermiteRailValue(t, a[1], ySlopes[i], b[1], ySlopes[i + 1], dz);
              rail.push([x, y, z]);
            }}
          }}
          return rail;
        }}

        function railControlPoints(entries, selector) {{
          return entries.map((entry) => selector(entry));
        }}

        function quadraticBezier1d(t, p0, p1, p2) {{
          const u = 1.0 - t;
          return u * u * p0 + 2.0 * u * t * p1 + t * t * p2;
        }}

        function cubicBezier1d(t, p0, p1, p2, p3) {{
          const u = 1.0 - t;
          return u * u * u * p0 + 3.0 * u * u * t * p1 + 3.0 * u * t * t * p2 + t * t * t * p3;
        }}

        function hermite1d(t, p0, m0, p1, m1) {{
          // Cubic Hermite: value p0->p1 with endpoint slopes m0, m1 (in t-space).
          const t2 = t * t;
          const t3 = t2 * t;
          const h00 = 2.0 * t3 - 3.0 * t2 + 1.0;
          const h10 = t3 - 2.0 * t2 + t;
          const h01 = -2.0 * t3 + 3.0 * t2;
          const h11 = t3 - t2;
          return h00 * p0 + h10 * m0 + h01 * p1 + h11 * m1;
        }}


        function smoothstep(t) {{ return 3.0 * t * t - 2.0 * t * t * t; }}

        function wingtipArcStations(sections) {{
          // Winglet = an elliptical arc (see wing_generator/genome.py + population_generator.py;
          // this MUST stay in sync with winglet_stations() there). Swept through phi in [0, arc]:
          //   spanOffset = ellipseLength * sin(phi)
          //   bend       = ellipseRadius * (1 - cos phi)        // zero initial slope -> C1 with wing
          //   the bend is rotated by ellipseRotation into vertical & horizontal parts
          //   the wing's exit sweep/dihedral slopes are continued for a smooth join
          //   chord scales down per station at scaleRate; pointy -> point (apex at pointyTipX),
          //   flat -> stops at flatTipChord. The section also thins toward a thin tip edge.
          const wingtip = DESIGN.wingtip;
          const length = wingtip.ellipse_length;
          const radius = wingtip.ellipse_radius;
          const theta = (wingtip.ellipse_rotation_deg || 0.0) * DEG;
          const arcAbs = Math.abs(wingtip.arc_angle_deg) * DEG;
          const hRate = wingtip.horizontal_rate || 0.0;
          const sRate = wingtip.scale_rate || 0.0;
          const stationCount = DESIGN.wingtip_sections;
          const isPointy = wingtip.is_pointy === true;
          const flatTipChordM = wingtip.flat_tip_chord_m || 0.1;
          const pointyTipXFrac = wingtip.pointy_tip_x_frac || 0.0;
          const spanReachM = length * Math.sin(arcAbs); // total winglet spanwise reach
          const minTipChordM = wingtip.min_tip_chord_m || {config.winglet_min_tip_chord_m};
          const minTipThicknessM = wingtip.min_tip_thickness_m || {config.winglet_min_tip_thickness_m};
          const tipThicknessM = wingtip.tip_thickness_m || {config.winglet_tip_thickness_m};

          const finalSection = sections[sections.length - 1];
          const previousSection = sections[sections.length - 2];
          const spanDeltaM = Math.max(
            finalSection.spanwise_position - previousSection.spanwise_position,
            1e-6
          );

          // Wing-exit slopes (per metre of span) continued for a tangent (C1) join.
          const sweepSlope =
            (finalSection.horizontal_displacement - previousSection.horizontal_displacement) / spanDeltaM;
          const dihedralSlope =
            (finalSection.vertical_displacement - previousSection.vertical_displacement) / spanDeltaM;

          const finalCoords = AIRFOILS[finalSection.airfoil_type];
          const baseThicknessM = profileThickness(finalCoords) * finalSection.chord_length;

          const stations = [];
          for (let i = 1; i <= stationCount; i += 1) {{
            const t = i / stationCount;
            const phi = arcAbs * t;
            const oneMinusCos = 1.0 - Math.cos(phi);
            const spanOffsetM = length * Math.sin(phi);
            const bend = radius * oneMinusCos;
            const verticalBend = Math.cos(theta) * bend;
            const horizontalBend = Math.sin(theta) * bend;
            // Extra winglet sweep applied with a zero-initial-slope (1 - cos) ramp so
            // horizontal_rate = 0 is exactly C1 and any value adds a crease-free sweep.
            const horizontalRateBend = hRate * length * oneMinusCos;
            const apex = isPointy ? pointyTipXFrac * spanReachM * smoothstep(t) : 0.0;

            // Per-station chord scale-down at scaleRate. Pointy necks all the way to a
            // point at the last station (normalised so it ALWAYS reaches minTipChord,
            // regardless of scaleRate — scaleRate only shapes the taper). Flat stops at
            // flatTipChord.
            const chordFactor = Math.pow(1.0 - sRate, i);
            let chordLengthM;
            if (isPointy) {{
              const rawEnd = Math.pow(1.0 - sRate, stationCount);
              const norm = (chordFactor - rawEnd) / Math.max(1e-6, 1.0 - rawEnd); // 1 -> 0
              chordLengthM = minTipChordM + (finalSection.chord_length - minTipChordM) * norm;
            }} else {{
              chordLengthM = Math.max(flatTipChordM, finalSection.chord_length * chordFactor);
            }}

            // Thickness thins smoothly from the wing section to the thin tip edge.
            const targetThicknessM = Math.max(
              minTipThicknessM,
              baseThicknessM + (tipThicknessM - baseThicknessM) * smoothstep(t)
            );

            const horizontalDisplacement =
              finalSection.horizontal_displacement +
              sweepSlope * spanOffsetM +
              horizontalRateBend +
              horizontalBend +
              apex;

            const verticalDisplacement =
              finalSection.vertical_displacement +
              dihedralSlope * spanOffsetM +
              verticalBend;

            stations.push({{
              section_index: DESIGN.num_sections - 1 + i,
              airfoil_type: finalSection.airfoil_type,
              spanwise_position: finalSection.spanwise_position + spanOffsetM,
              chord_length: chordLengthM,
              section_scale: chordLengthM / {config.root_chord_m},
              target_thickness_m: targetThicknessM,
              root_pitch_angle_deg: finalSection.root_pitch_angle_deg,
              horizontal_displacement: horizontalDisplacement,
              vertical_displacement: verticalDisplacement,
            }});
          }}
          return stations;
        }}

        const loftEntries = [];

        for (const section of DESIGN.sections) {{
          loftEntries.push(loftEntry(section));
        }}

        for (const station of wingtipArcStations(DESIGN.sections)) {{
          loftEntries.push(loftEntry(station));
        }}

        const sortedEntries = [...loftEntries].sort((a, b) => a.height - b.height);
        const loftStations = sortedEntries.map((entry) => Loft.station(entry.profile, entry.height));

        // Guard rails: section-local negative-X = leading edge, positive-X =
        // trailing edge. A center rail also carries the smoothed dihedral path.
        // The rails are sampled splines through the section parameters, so the
        // loft no longer has to infer the LE/TE paths from profile stacking alone.
        const leadingEdgeRail = smoothRail(
          railControlPoints(sortedEntries, (entry) => [
            entry.bounds.minX,
            entry.bounds.centerY,
            entry.height,
          ])
        );
        const trailingEdgeRail = smoothRail(
          railControlPoints(sortedEntries, (entry) => [
            entry.bounds.maxX,
            entry.bounds.centerY,
            entry.height,
          ])
        );
        const centerRail = smoothRail(
          railControlPoints(sortedEntries, (entry) => [
            entry.bounds.centerX,
            entry.bounds.centerY,
            entry.height,
          ])
        );

        const loftedWing = Loft.withGuideRails(loftStations, [
          Loft.leftRail(leadingEdgeRail),
          Loft.rightRail(trailingEdgeRail),
          Loft.centerRail(centerRail),
        ], {{
          axis: "Z",
          samples: Math.max(72, loftStations.length * 3),
          railSamples: 96,
          edgeLength: DESIGN.forgecad.mesh_edge_length_mm,
          boundsPadding: DESIGN.forgecad.bounds_padding_mm,
        }});

        // Reorient to the global frame: X = chordwise, Y = spanwise, Z = vertical (up).
        const wing = loftedWing.rotateX(90).color("#4F8FD6");

        verify.notEmpty("generated wing solid", wing);
        verify.greaterThan("wing body count", wing.numBodies(), 0);
        verify.greaterThan("wing volume", wing.volume(), 0);

        return {{
          Wing: wing,
        }};
        """
    ).lstrip()
